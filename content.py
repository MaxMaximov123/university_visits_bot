def get_random_content(settings):
    available = []
    for key, (label, items) in CONTENT_MAP.items():
        if settings.get(key) == "1":
            available.extend([(label, item) for item in items])
    if not available:
        return None
    return random.choice(available)


def get_weather_moscow():
    try:
        url = "https://wttr.in/Moscow?format=%t+%C&lang=ru"
        req = urllib.request.Request(url, headers={"User-Agent": "curl/7.0"})
        with urllib.request.urlopen(req, timeout=5) as resp:
            data = resp.read().decode("utf-8").strip()
            return data
    except Exception:
        return None
