def format_date_ru(d):
    weekday = WEEKDAY_NAMES[d.weekday()]
    month = MONTH_NAMES[d.month]
    return f"{weekday}, {d.day} {month} {d.year}"


def declension(n, one, few, many):
    n_abs = abs(n) % 100
    if 11 <= n_abs <= 19:
        return f"{n} {many}"
    last = n_abs % 10
    if last == 1:
        return f"{n} {one}"
    if 2 <= last <= 4:
        return f"{n} {few}"
    return f"{n} {many}"


